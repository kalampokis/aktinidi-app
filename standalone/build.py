#!/usr/bin/env python3
"""Builds index.html from the shared page and copies the invoice prompt to the server function."""
import base64
import json
import re
from pathlib import Path

here = Path(__file__).parent
page = (here.parent / "aktinidi.html").read_text(encoding="utf-8")

# A public key is fine to publish; a secret one would hand the whole database to anyone.
config = (here / "config.js").read_text(encoding="utf-8")
key = re.search(r'supabaseKey:\s*"([^"]*)"', config).group(1)
role = ""
if key.count(".") == 2:
    part = key.split(".")[1]
    role = json.loads(base64.urlsafe_b64decode(part + "=" * (-len(part) % 4))).get("role", "")
if key.startswith("sb_secret") or role == "service_role":
    raise SystemExit("config.js has a secret key. Use the publishable (anon) key instead.")

head = """<!doctype html>
<html lang="el"><head><meta charset="utf-8">
<meta name="viewport" content="width=device-width,initial-scale=1,viewport-fit=cover">
<meta name="theme-color" content="#3c6b1c">
<meta name="apple-mobile-web-app-capable" content="yes">
<link rel="manifest" href="manifest.webmanifest">
<link rel="apple-touch-icon" href="icon-192.png">
<style>:root{padding-top:env(safe-area-inset-top,0px);padding-bottom:env(safe-area-inset-bottom,0px)}body{margin:0}img{max-width:100%}[hidden]{display:none!important}</style>
<script src="config.js"></script>
<script src="vendor/supabase.js"></script>
<script src="local-runtime.js"></script>
</head><body>
"""
(here / "index.html").write_text(head + page + "\n</body></html>\n", encoding="utf-8")

prompt = re.search(r"const SCAN_PROMPT=(`.*?`);", page, re.S).group(1)
(here / "supabase/functions/read-invoice/prompt.ts").parent.mkdir(parents=True, exist_ok=True)
(here / "supabase/functions/read-invoice/prompt.ts").write_text(
    "// Generated by build.py from aktinidi.html. Do not edit here.\nexport const SCAN_PROMPT = " + prompt + ";\n",
    encoding="utf-8",
)
print("index.html and prompt.ts written")
